-- 서비스 원천 데이터 (학습자료 마켓을 가정)
CREATE TABLE member (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    joined_at TIMESTAMP NOT NULL
);

CREATE TABLE login_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT    NOT NULL REFERENCES member (id),
    occurred_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_login_event_occurred_at ON login_event (occurred_at, member_id);

CREATE TABLE purchase (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT        NOT NULL REFERENCES member (id),
    amount    NUMERIC(12, 0) NOT NULL CHECK (amount > 0),
    status    VARCHAR(20)   NOT NULL CHECK (status IN ('PAID', 'REFUNDED')),
    paid_at   TIMESTAMP     NOT NULL
);
CREATE INDEX idx_purchase_paid_at ON purchase (paid_at);

CREATE TABLE material_download (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     BIGINT    NOT NULL REFERENCES member (id),
    downloaded_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_material_download_downloaded_at ON material_download (downloaded_at);

-- 리포트 결과
CREATE TABLE kpi_snapshot (
    report_date DATE           NOT NULL,
    kpi_code    VARCHAR(50)    NOT NULL,
    kpi_value   NUMERIC(18, 2) NOT NULL,
    computed_at TIMESTAMP      NOT NULL,
    PRIMARY KEY (report_date, kpi_code)
);

CREATE TABLE report_run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date DATE         NOT NULL,
    trigger_type VARCHAR(20) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    message     VARCHAR(1000),
    started_at  TIMESTAMP    NOT NULL,
    finished_at TIMESTAMP
);
CREATE INDEX idx_report_run_report_date ON report_run (report_date);
